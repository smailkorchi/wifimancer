#!/usr/bin/env bash
# Render Resources/icon.svg into all .appiconset slots and rebuild Contents.json.
set -euo pipefail

cd "$(dirname "$0")/.."

SVG="Resources/icon.svg"
SET="Resources/Assets.xcassets/AppIcon.appiconset"
TMP="build/iconwork"

[ -f "$SVG" ] || { echo "missing $SVG"; exit 1; }
mkdir -p "$TMP" "$SET"

# Render master 1024 PNG once.
rsvg-convert -w 1024 -h 1024 "$SVG" -o "$TMP/icon_1024.png"

# Slot map: target_size  output_filename
SLOTS=(
    "16    icon_16x16.png"
    "32    icon_16x16@2x.png"
    "32    icon_32x32.png"
    "64    icon_32x32@2x.png"
    "128   icon_128x128.png"
    "256   icon_128x128@2x.png"
    "256   icon_256x256.png"
    "512   icon_256x256@2x.png"
    "512   icon_512x512.png"
    "1024  icon_512x512@2x.png"
)

for entry in "${SLOTS[@]}"; do
    set -- $entry
    SIZE=$1
    NAME=$2
    sips -Z "$SIZE" "$TMP/icon_1024.png" --out "$SET/$NAME" >/dev/null
done

cat > "$SET/Contents.json" <<JSON
{
  "images" : [
    { "idiom" : "mac", "scale" : "1x", "size" : "16x16",   "filename" : "icon_16x16.png" },
    { "idiom" : "mac", "scale" : "2x", "size" : "16x16",   "filename" : "icon_16x16@2x.png" },
    { "idiom" : "mac", "scale" : "1x", "size" : "32x32",   "filename" : "icon_32x32.png" },
    { "idiom" : "mac", "scale" : "2x", "size" : "32x32",   "filename" : "icon_32x32@2x.png" },
    { "idiom" : "mac", "scale" : "1x", "size" : "128x128", "filename" : "icon_128x128.png" },
    { "idiom" : "mac", "scale" : "2x", "size" : "128x128", "filename" : "icon_128x128@2x.png" },
    { "idiom" : "mac", "scale" : "1x", "size" : "256x256", "filename" : "icon_256x256.png" },
    { "idiom" : "mac", "scale" : "2x", "size" : "256x256", "filename" : "icon_256x256@2x.png" },
    { "idiom" : "mac", "scale" : "1x", "size" : "512x512", "filename" : "icon_512x512.png" },
    { "idiom" : "mac", "scale" : "2x", "size" : "512x512", "filename" : "icon_512x512@2x.png" }
  ],
  "info" : { "author" : "xcode", "version" : 1 }
}
JSON

echo "Wrote 10 icon slots to $SET"
